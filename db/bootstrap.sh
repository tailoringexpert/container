#!/bin/sh

OUTFILE=/app/bootstrap.sql
cat /dev/null > $OUTFILE

if [ -f ${SECRETS_FILE} ]; then
  echo "Using $SECRETS_FILE"
  export $(grep -v '^#' $SECRETS_FILE | xargs -0)
fi

printenv 
if [ ! -z ${KEYCLOAKDB_DATABASE+x} ]; then
  echo "# keycloak" >> $OUTFILE
  echo "CREATE USER IF NOT EXISTS  '$KEYCLOAKDB_USER' IDENTIFIED BY '$KEYCLOAKDB_PASSWORD';" >> $OUTFILE
  echo "CREATE DATABASE IF NOT EXISTS $KEYCLOAKDB_DATABASE CHARACTER SET utf8mb4;" >> $OUTFILE
  echo "GRANT ALL PRIVILEGES ON $KEYCLOAKDB_DATABASE.* TO '$KEYCLOAKDB_USER'@'%';" >> $OUTFILE
  echo "" >> $OUTFILE
fi

echo "# platform" >> $OUTFILE
echo "CREATE USER IF NOT EXISTS '$TAILORINGEXPERTDB_USER' IDENTIFIED BY '$TAILORINGEXPERTDB_PASSWORD';" >> $OUTFILE
echo "CREATE DATABASE IF NOT EXISTS $TAILORINGEXPERTDB_DATABASE CHARACTER SET utf8mb4;" >> $OUTFILE
echo "GRANT ALL PRIVILEGES ON $TAILORINGEXPERTDB_DATABASE.* TO '$TAILORINGEXPERTDB_USER'@'%';" >> $OUTFILE
echo "" >> $OUTFILE 

if [ ! -z ${DEMODB_DATABASE+x} ];
then
  echo "# demo" >> $OUTFILE
  echo "CREATE USER IF NOT EXISTS  '$DEMODB_USER' IDENTIFIED BY '$DEMODB_PASSWORD';" >> $OUTFILE
  echo "CREATE DATABASE IF NOT EXISTS $DEMODB_DATABASE CHARACTER SET utf8mb4;" >> $OUTFILE
  echo "GRANT ALL PRIVILEGES ON $DEMODB_DATABASE.* TO '$DEMODB_USER'@'%';" >> $OUTFILE
  echo "" >> $OUTFILE
else
  echo "DEMO SQL script not created"
fi


